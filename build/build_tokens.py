"""Design tokens emitted for the site build: CSS custom properties, a JSON
map for tooling, and a Tailwind theme fragment."""
import sys, os, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import brand as B

SCALE = {
    "display": ("clamp(2.75rem, 1.6rem + 4.4vw, 4.75rem)", "1.06", "Source Serif Pro", 600),
    "h1": ("clamp(2.25rem, 1.5rem + 2.8vw, 3.375rem)", "1.10", "Source Serif Pro", 600),
    "h2": ("clamp(1.75rem, 1.3rem + 1.8vw, 2.5rem)", "1.16", "Source Serif Pro", 600),
    "h3": ("clamp(1.375rem, 1.15rem + 0.9vw, 1.75rem)", "1.24", "Source Serif Pro", 600),
    "lede": ("clamp(1.125rem, 1rem + 0.6vw, 1.375rem)", "1.62", "Source Serif Pro", 400),
    "body": ("1.0625rem", "1.68", "Source Sans Pro", 400),
    "small": ("0.9375rem", "1.55", "Source Sans Pro", 400),
    "label": ("0.8125rem", "1.3", "Source Sans Pro", 600),
}
SPACE = [2, 4, 8, 12, 16, 24, 32, 48, 64, 96, 128, 192]
RADIUS = {"sm": 6, "md": 12, "lg": 20, "xl": 32, "pill": 999}
SHADOW = {
    "sm": "0 1px 2px rgba(15,30,28,.06), 0 1px 1px rgba(15,30,28,.04)",
    "md": "0 4px 12px rgba(15,30,28,.08), 0 2px 4px rgba(15,30,28,.04)",
    "lg": "0 18px 48px rgba(15,30,28,.12), 0 6px 14px rgba(15,30,28,.06)",
}


def css():
    lines = [
        "/* Aromatabs design tokens - generated by build/build_tokens.py */",
        ":root {",
        "  /* colour */",
    ]
    for k, v in B.C.items():
        if k in ("white", "black"):
            continue
        lines.append(f"  --at-{k}: {v};")
    lines += [
        "",
        "  /* semantic */",
        "  --at-bg: var(--at-linen);",
        "  --at-surface: var(--at-cloud);",
        "  --at-text: var(--at-ink);",
        "  --at-text-muted: color-mix(in srgb, var(--at-ink) 68%, transparent);",
        "  --at-accent: var(--at-ember);",
        "  --at-link: var(--at-brand600);",
        "  --at-border: color-mix(in srgb, var(--at-ink) 12%, transparent);",
        "",
        "  /* type */",
        '  --at-font-display: "Source Serif Pro", ui-serif, Georgia, serif;',
        '  --at-font-body: "Source Sans Pro", ui-sans-serif, system-ui, sans-serif;',
    ]
    for name, (size, lh, fam, weight) in SCALE.items():
        lines.append(f"  --at-{name}-size: {size};")
        lines.append(f"  --at-{name}-leading: {lh};")
        lines.append(f"  --at-{name}-weight: {weight};")
    lines.append("")
    lines.append("  /* space */")
    for s in SPACE:
        lines.append(f"  --at-space-{s}: {s / 16:.4g}rem;")
    lines.append("")
    lines.append("  /* radius + elevation */")
    for k, v in RADIUS.items():
        lines.append(f"  --at-radius-{k}: {v}px;")
    for k, v in SHADOW.items():
        lines.append(f"  --at-shadow-{k}: {v};")
    lines += ["}", "",
              '[data-theme="dark"], :root:not([data-theme="light"]) {',
              "  /* only the semantic layer flips */", "}",
              '@media (prefers-color-scheme: dark) {',
              '  :root:not([data-theme="light"]) {',
              "    --at-bg: var(--at-ink);",
              "    --at-surface: var(--at-deep);",
              "    --at-text: var(--at-cloud);",
              "    --at-text-muted: color-mix(in srgb, var(--at-cloud) 70%, transparent);",
              "    --at-link: var(--at-brand300);",
              "    --at-border: color-mix(in srgb, var(--at-cloud) 16%, transparent);",
              "  }", "}",
              '[data-theme="dark"] {',
              "  --at-bg: var(--at-ink);",
              "  --at-surface: var(--at-deep);",
              "  --at-text: var(--at-cloud);",
              "  --at-text-muted: color-mix(in srgb, var(--at-cloud) 70%, transparent);",
              "  --at-link: var(--at-brand300);",
              "  --at-border: color-mix(in srgb, var(--at-cloud) 16%, transparent);",
              "}"]
    return "\n".join(lines) + "\n"


def tokens_json():
    return json.dumps({
        "name": "Aromatabs",
        "tagline": B.TAGLINE.title(),
        "descriptor": B.DESCRIPTOR,
        "color": {k: v for k, v in B.C.items() if k not in ("white", "black")},
        "gradient": {
            "mark": [B.C["brand"], B.C["deep"]],
            "plate": [B.C["deep"], B.C["ink"]],
            "reverseMark": [B.C["cloud"], B.C["mist"]],
        },
        "font": {
            "display": "Source Serif Pro",
            "body": "Source Sans Pro",
            "fallbackDisplay": "ui-serif, Georgia, serif",
            "fallbackBody": "ui-sans-serif, system-ui, sans-serif",
        },
        "scale": {k: {"size": v[0], "leading": v[1], "family": v[2],
                      "weight": v[3]} for k, v in SCALE.items()},
        "space": {str(s): f"{s / 16:.4g}rem" for s in SPACE},
        "radius": RADIUS,
        "shadow": SHADOW,
    }, indent=2) + "\n"


def tailwind():
    colors = ",\n".join(f'          "{k}": "{v}"' for k, v in B.C.items()
                        if k not in ("white", "black"))
    return f"""// Aromatabs Tailwind theme fragment - generated by build/build_tokens.py
/** @type {{import('tailwindcss').Config}} */
module.exports = {{
  theme: {{
    extend: {{
      colors: {{
        at: {{
{colors}
        }}
      }},
      fontFamily: {{
        display: ['"Source Serif Pro"', 'ui-serif', 'Georgia', 'serif'],
        body: ['"Source Sans Pro"', 'ui-sans-serif', 'system-ui', 'sans-serif']
      }},
      borderRadius: {{
{chr(10).join(f'        "{k}": "{v}px",' for k, v in RADIUS.items())}
      }},
      boxShadow: {{
{chr(10).join(f'        "{k}": "{v}",' for k, v in SHADOW.items())}
      }}
    }}
  }}
}};
"""


def main():
    made = []
    for rel, content in (("brand/tokens.css", css()),
                         ("brand/tokens.json", tokens_json()),
                         ("brand/tailwind.theme.cjs", tailwind())):
        path = os.path.join(B.OUT, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, "w").write(content)
        made.append(rel)
    return made


if __name__ == "__main__":
    for f in main():
        print(f)
