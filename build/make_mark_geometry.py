"""Emit the mark's geometry as TypeScript so the site and the artwork are
drawn from the same numbers. Regenerate after changing the mark in brand.py."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import brand as B

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "components", "brand", "mark-geometry.ts")


def main():
    cx, cy, r = B.DROP
    ripples = [
        f"  {{ d: 'M{50 - hw:.1f},{y:.1f} Q50,{y + dep:.1f} {50 + hw:.1f},{y:.1f}' }},"
        for y, hw, dep in B.RIPPLES
    ]
    body = f"""// Generated by build/make_mark_geometry.py - do not edit by hand.
// The Aromatabs mark: a tab dissolving into still water. Drawn on a 100x100
// grid so it scales to any size from a 16px favicon upward.

export const SQUIRCLE = '{B.superellipse(50, 50, 50, 50, steps=32)}';

export const DROP = {{ cx: {cx}, cy: {cy}, r: {r} }} as const;

export const RIPPLES = [
{chr(10).join(ripples)}
] as const;

export const STROKE = {B.STROKE};
"""
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fh:
        fh.write(body)
    print(f"components/brand/mark-geometry.ts  ({len(body)} bytes)")


if __name__ == "__main__":
    main()
